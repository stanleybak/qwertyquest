#!/usr/bin/env python3
"""Write version.json and js/version.js: a hash of every file the game page loads.

A running game fetches version.json now and then; when the hash differs from
the one it started with, it offers to update. The pre-commit hook in
.githooks/ runs this, so the hash changes whenever the game does.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAMP = ROOT / "js" / "version.js"  # the same hash, built into the code, so a running game knows its own version
files = [ROOT / "index.html", ROOT / "style.css", *sorted((ROOT / "js").glob("*.js")), *sorted((ROOT / "vendor").glob("*.js"))]
files = [f for f in files if f != STAMP]
h = hashlib.sha256()
for f in files:
    h.update(f.relative_to(ROOT).as_posix().encode())
    h.update(f.read_bytes())
ver = h.hexdigest()[:16]
names = [f.relative_to(ROOT).as_posix() for f in files] + ["js/version.js"]
for out, text in ((ROOT / "version.json", json.dumps({"hash": ver, "files": names}) + "\n"),
                  (STAMP, f"// GENERATED by tools/stamp_version.py.\nexport default {json.dumps(ver)};\n")):
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
print("version", ver)
